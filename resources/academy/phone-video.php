## Light

- **Face a window.** Soft daylight from the front is the most flattering free light.
- Avoid having a bright window **behind** you; you'll become a silhouette.
- At night, place a lamp or ring light slightly above eye level, in front of you.
- Turn off mixed coloured lights that make skin look strange.

## Sound

- Film in a quiet room with soft things (curtains, sofa, bed) to reduce echo.
- Keep the mic close to your mouth.
- Turn off fans and TVs; close windows facing the road.
- Record a 5-second test and listen with headphones before the real take.

> **Action step:** Film the same sentence in three spots in your home and choose the best light and sound.
