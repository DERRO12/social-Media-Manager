A Google Business Profile is the free listing that appears on **Google Maps** and in the map results of Google Search. For local businesses it is often the **most important** online presence, more than social media.

## What people do from your profile

- Call you directly
- Get directions
- Visit your website or WhatsApp
- Read reviews and look at photos
- See opening hours

## How Google chooses who shows up

Google has said local results are mainly based on three things:

1. **Relevance:** how well your profile matches the search.
2. **Distance:** how close you are to the searcher or the area searched.
3. **Prominence:** how well known you are, including reviews and your presence across the web.

You can't change distance, but you can improve relevance and prominence a lot.

> **Action step:** Search Google for your main service + your town. Note who appears in the map and what their profiles have that yours doesn't.
